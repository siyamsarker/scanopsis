// A restore recreates the schema inside one transaction: it drops the tables
// (DropApplicationTables), replays the migrations up to the version of the
// backup (ReplayMigrations), loads the data, replays the newer migrations and
// records them the way goose does (RecordGooseVersions). PostgreSQL runs DDL
// transactionally, so a failure at any step leaves the database as it was.
//
// Goose cannot run inside a transaction it does not own, so the replay reads
// the Up part of the embedded migrations itself and runs each statement in
// the caller's transaction. Migrations marked NO TRANSACTION build indexes
// with CONCURRENTLY, which PostgreSQL refuses inside a transaction; on tables
// that were just created and are locked by the transaction anyway it gains
// nothing, so the replay builds those indexes without it.

// gooseVersionTable creates the version table exactly as goose v3 does for
// PostgreSQL, so goose accepts a table recorded by RecordGooseVersions.
const gooseVersionTable = `CREATE TABLE goose_db_version (
		id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
		version_id bigint NOT NULL,
		is_applied boolean NOT NULL,
		tstamp timestamp NOT NULL DEFAULT now()
	)`

// migration is the Up part of one embedded migration file.
type migration struct {
	version int64
	name    string
	up      []string
}

// embeddedMigrations parses the embedded migrations once, in version order.
var embeddedMigrations = sync.OnceValues(func() ([]migration, error) {
	entries, err := fs.ReadDir(migrations, "migrations")
	if err != nil {
		return nil, err
	}
	var ms []migration
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || path.Ext(name) != ".sql" {
			continue
		}
		prefix, _, _ := strings.Cut(name, "_")
		version, err := strconv.ParseInt(prefix, 10, 64)
		if err != nil || version < 1 {
			return nil, fmt.Errorf("migration %s: no version number in the name", name)
		}
		src, err := fs.ReadFile(migrations, "migrations/"+name)
		if err != nil {
			return nil, err
		}
		up, err := parseUp(string(src))
		if err != nil {
			return nil, fmt.Errorf("migration %s: %w", name, err)
		}
		ms = append(ms, migration{version: version, name: name, up: up})
	}
	if len(ms) == 0 {
		return nil, errors.New("no embedded migrations")
	}
	slices.SortFunc(ms, func(a, b migration) int { return cmp.Compare(a.version, b.version) })
	for i := 1; i < len(ms); i++ {
		if ms[i].version == ms[i-1].version {
			return nil, fmt.Errorf("migrations %s and %s have the same version", ms[i-1].name, ms[i].name)
		}
	}
	return ms, nil
})

// LatestVersion returns the version of the newest embedded migration, the
// schema version this build migrates to.
func LatestVersion() int64 {
	ms, err := embeddedMigrations()
	if err != nil {
		// The migrations are part of the binary and parsed by the tests.
		panic("store: " + err.Error())
	}
	return ms[len(ms)-1].version
}

// SchemaVersion returns the highest migration version goose recorded as
// applied in the database, 0 if none was.
func SchemaVersion(ctx context.Context, db DBTX) (int64, error) {
	var v int64
	err := db.QueryRow(ctx, `SELECT coalesce(max(version_id), 0) FROM goose_db_version WHERE is_applied`).Scan(&v)
	if err != nil {
		return 0, fmt.Errorf("read schema version: %w", err)
	}
	return v, nil
}

// ReplayMigrations runs, in tx, the Up part of every embedded migration with
// from < version <= to, in version order. NO TRANSACTION is ignored and
// CONCURRENTLY is removed from CREATE INDEX and DROP INDEX statements, so
// every statement runs inside tx. Statements are sent with the simple
// protocol, as goose sends them. It returns an error naming the migration
// whose statement failed; tx must then be rolled back. A range outside 0 to
// LatestVersion is refused before anything runs.
func ReplayMigrations(ctx context.Context, tx pgx.Tx, from, to int64) error {
	ms, err := embeddedMigrations()
	if err != nil {
		return err
	}
	if latest := ms[len(ms)-1].version; from < 0 || from > to || to > latest {
		return fmt.Errorf("replay migrations after version %d up to %d: the versions must be in order, from 0 to %d", from, to, latest)
	}
	for _, m := range ms {
		if m.version <= from || m.version > to {
			continue
		}
		for i, stmt := range m.up {
			if _, err := tx.Exec(ctx, withoutConcurrently(stmt), pgx.QueryExecModeSimpleProtocol); err != nil {
				return fmt.Errorf("replay migration %s, statement %d: %w", m.name, i+1, err)
			}
		}
	}
	return nil
}

// RecordGooseVersions drops and recreates goose's version table in tx, with
// the same definition and rows as goose itself writes: version 0, then every
// embedded migration up to upTo, each applied. Goose then treats those
// migrations as applied and applies only the newer ones.
func RecordGooseVersions(ctx context.Context, tx pgx.Tx, upTo int64) error {
	ms, err := embeddedMigrations()
	if err != nil {
		return err
	}
	if latest := ms[len(ms)-1].version; upTo < 0 || upTo > latest {
		return fmt.Errorf("record migration versions up to %d: the version must be from 0 to %d", upTo, latest)
	}
	for _, q := range []string{`DROP TABLE IF EXISTS goose_db_version`, gooseVersionTable} {
		if _, err := tx.Exec(ctx, q); err != nil {
			return fmt.Errorf("create the migration version table: %w", err)
		}
	}
	versions := []int64{0}
	for _, m := range ms {
		if m.version <= upTo {
			versions = append(versions, m.version)
		}
	}
	// One row at a time, like goose, so the ids follow the versions.
	for _, v := range versions {
		if _, err := tx.Exec(ctx, `INSERT INTO goose_db_version (version_id, is_applied) VALUES ($1, true)`, v); err != nil {
			return fmt.Errorf("record migration version %d: %w", v, err)
		}
	}
	return nil
}

// DropApplicationTables drops, in tx and with CASCADE, every table that the
// current role owns in the schema the migrations create their tables in
// (current_schema(): public unless the database URL sets another
// search_path), and goose's version table there. Tables of other roles in
// that schema are left alone.
func DropApplicationTables(ctx context.Context, tx pgx.Tx) error {
	rows, err := tx.Query(ctx, `
		SELECT n.nspname, c.relname FROM pg_class c
		JOIN pg_namespace n ON n.oid = c.relnamespace
		WHERE n.nspname = current_schema() AND c.relkind IN ('r', 'p')
		  AND (c.relowner = (SELECT oid FROM pg_roles WHERE rolname = current_user) OR c.relname = 'goose_db_version')
		ORDER BY c.relname`)
	if err != nil {
		return fmt.Errorf("list tables to drop: %w", err)
	}
	tables, err := pgx.CollectRows(rows, func(row pgx.CollectableRow) (string, error) {
		var schema, name string
		err := row.Scan(&schema, &name)
		return pgx.Identifier{schema, name}.Sanitize(), err
	})
	if err != nil {
		return fmt.Errorf("list tables to drop: %w", err)
	}
	if len(tables) == 0 {
		return nil
	}
	if _, err := tx.Exec(ctx, "DROP TABLE IF EXISTS "+strings.Join(tables, ", ")+" CASCADE"); err != nil {
		return fmt.Errorf("drop tables: %w", err)
	}
	return nil
}

// concurrentIndex matches CONCURRENTLY right after the keywords of a CREATE
// INDEX or DROP INDEX statement, so the word is not touched anywhere else.
var concurrentIndex = regexp.MustCompile(`(?i)^((?:CREATE\s+(?:UNIQUE\s+)?|DROP\s+)INDEX)\s+CONCURRENTLY\b`)

// withoutConcurrently returns stmt without CONCURRENTLY if it is a CREATE
// INDEX or DROP INDEX statement, unchanged otherwise.
func withoutConcurrently(stmt string) string {
	return concurrentIndex.ReplaceAllString(stmt, "$1")
}

// parseUp returns the statements of the Up part of a goose SQL migration,
// split the way goose splits them: a statement ends at a line whose last
// word before any "--" comment ends with a semicolon, or at
// "-- +goose StatementEnd" when it started with "-- +goose StatementBegin".
// Comment lines and blank lines before a statement are dropped. The Down
// part is skipped. "-- +goose NO TRANSACTION" is accepted and has no effect;
// any other annotation is an error.
func parseUp(src string) ([]string, error) {
	const (
		start = iota // before "-- +goose Up"
		up
		upBlock // between StatementBegin and StatementEnd in the Up part
		down
		downBlock
	)
	state := start
	var stmts []string
	var buf strings.Builder
	for n, line := range strings.Split(src, "\n") {
		line = strings.TrimSuffix(line, "\r")
		trimmed := strings.TrimSpace(line)
		if strings.HasPrefix(trimmed, "--") && strings.Contains(line, "+goose") {
			a, err := gooseAnnotation(line)
			if err != nil {
				return nil, fmt.Errorf("line %d: %w", n+1, err)
			}
			switch {
			case a == "up" && state == start:
				state = up
			case a == "up":
				return nil, fmt.Errorf("line %d: duplicate -- +goose Up", n+1)
			case a == "down" && state == up:
				if buf.Len() > 0 {
					return nil, fmt.Errorf("line %d: statement before -- +goose Down lacks its semicolon", n+1)
				}
				state = down
			case a == "down":
				return nil, fmt.Errorf("line %d: -- +goose Down must follow -- +goose Up and a finished statement", n+1)
			case a == "statementbegin" && (state == up || state == down) && buf.Len() == 0:
				state++ // upBlock or downBlock
			case a == "statementbegin":
				return nil, fmt.Errorf("line %d: -- +goose StatementBegin must follow -- +goose Up or Down and a finished statement", n+1)
			case a == "statementend" && state == upBlock:
				stmts = append(stmts, strings.TrimSpace(buf.String()))
				buf.Reset()
				state = up
			case a == "statementend" && state == downBlock:
				state = down
			case a == "statementend":
				return nil, fmt.Errorf("line %d: -- +goose StatementEnd without -- +goose StatementBegin", n+1)
			case a == "no transaction":
				// Every statement runs in the caller's transaction.
			}
			continue
		}
		if buf.Len() == 0 && (trimmed == "" || strings.HasPrefix(trimmed, "--")) {
			continue
		}
		switch state {
		case start:
			return nil, fmt.Errorf("line %d: statement before -- +goose Up", n+1)
		case down, downBlock:
			continue
		}
		buf.WriteString(line)
		buf.WriteByte('\n')
		if state == up && endsWithSemicolon(line) {
			stmts = append(stmts, strings.TrimSpace(buf.String()))
			buf.Reset()
		}
	}
	switch {
	case state == start:
		return nil, errors.New("no -- +goose Up annotation")
	case state == upBlock || state == downBlock:
		return nil, errors.New("-- +goose StatementBegin without -- +goose StatementEnd")
	case buf.Len() > 0:
		return nil, fmt.Errorf("last statement lacks its semicolon: %.60q", strings.TrimSpace(buf.String()))
	}
	return stmts, nil
}

// gooseAnnotation returns the lower-case annotation of a "-- +goose" line.
func gooseAnnotation(line string) (string, error) {
	if strings.TrimLeft(line, " \t") != line {
		return "", fmt.Errorf("annotation %q has leading whitespace", line)
	}
	a := strings.TrimSpace(strings.Replace(strings.TrimPrefix(line, "--"), "+goose", "", 1))
	switch a = strings.ToLower(a); a {
	case "up", "down", "statementbegin", "statementend", "no transaction":
		return a, nil
	}
	return "", fmt.Errorf("unsupported annotation %q", line)
}

// endsWithSemicolon reports whether the last word of line before any "--"
// comment ends with a semicolon, as goose decides where a statement ends.
func endsWithSemicolon(line string) bool {
	prev := ""
	for word := range strings.FieldsSeq(line) {
		if strings.HasPrefix(word, "--") {
			break
		}
		prev = word
	}
	return strings.HasSuffix(prev, ";")
}
